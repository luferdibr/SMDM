# core/observability/logger.py
# =========================================================

import logging

# =========================================================
# CONFIG
# =========================================================

DEFAULT_LEVEL = logging.INFO

DEFAULT_FORMAT = (

    "%(asctime)s "

    "[%(levelname)s] "

    "%(message)s"
)

# =========================================================
# ROOT CONFIG
# =========================================================

logging.basicConfig(

    level=DEFAULT_LEVEL,

    format=DEFAULT_FORMAT,
)

# =========================================================
# GET LOGGER
# =========================================================

def get_logger(
    name,
):

    return logging.getLogger(
        str(name)
    )

# =========================================================
# DEFAULT LOGGER
# =========================================================

LOGGER = get_logger(
    "SMDM"
)